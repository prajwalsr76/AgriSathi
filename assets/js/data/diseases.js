// Find the closest knowledge-base entry for a free-text disease name (used for Expert mode).
export function matchDisease(crop, text) {
  if (!text) return null;
  const t = text.toLowerCase();
  let best = null, bestScore = 0;
  for (const [k, d] of Object.entries(DISEASES)) {
    let s = 0;
    const words = (d.name.en + ' ' + d.pathogen).toLowerCase().replace(/[()/,"–-]/g, ' ').split(/\s+/).filter(w => w.length > 3);
    for (const w of words) if (t.includes(w)) s += 1;
    if (d.name.en.toLowerCase() === t) s += 5;
    if (crop && d.crop === crop) s += 1.5; else if (crop) s -= 2;
    if (d.type === 'healthy' && !/healthy/.test(t)) s -= 5;
    if (s > bestScore) { bestScore = s; best = k; }
  }
  return bestScore >= 2.5 ? best : null;
}
